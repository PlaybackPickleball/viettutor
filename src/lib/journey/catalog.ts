export function getJourneyUnit(id: string): JourneyUnit | undefined {
  return JOURNEY_UNITS.find((u) => u.id === id);
}

export function getJourneyLesson(id: string): JourneyLesson | undefined {
  for (const unit of JOURNEY_UNITS) {
    const lesson = unit.lessons.find((l) => l.id === id);
    if (lesson) return lesson;
  }
  return undefined;
}

export function allLiveJourneyLessons(): JourneyLesson[] {
  return JOURNEY_UNITS.flatMap((u) => u.lessons.filter((l) => l.kind === "live"));
}
